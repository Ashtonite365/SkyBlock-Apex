package dev.ashtonite365.apex.annotations.process

import com.google.auto.service.AutoService
import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies
import com.google.devtools.ksp.processing.KSPLogger
import com.google.devtools.ksp.processing.Resolver
import com.google.devtools.ksp.processing.SymbolProcessor
import com.google.devtools.ksp.processing.SymbolProcessorEnvironment
import com.google.devtools.ksp.processing.SymbolProcessorProvider
import com.google.devtools.ksp.symbol.KSAnnotated
import com.google.devtools.ksp.symbol.KSClassDeclaration
import java.util.TreeSet

class CompatMetaProcessor(val logger: KSPLogger, val codeGenerator: CodeGenerator, val sourceSetName: String) :
	SymbolProcessor {
	private var written = false

	override fun process(resolver: Resolver): List<KSAnnotated> {
		if (written) return emptyList()
		val ownPackage = "dev.ashtonite365.apex.annotations.generated.$sourceSetName"
		val sources = resolver.getAllFiles().toList()
		val claimed = TreeSet<String>()
		sources.mapTo(claimed) { it.packageName.asString() }
		claimed += ownPackage

		val entries = sources.flatMap { it.declarations }
			.filterIsInstance<KSClassDeclaration>()
			.filter { decl ->
				decl.annotations.any {
					it.annotationType.resolve().declaration.qualifiedName?.asString() == "dev.ashtonite365.apex.util.compatloader.CompatEntry"
				}
			}
			.toList()

		if (entries.isEmpty()) return emptyList()
		val entry = entries.singleOrNull()
		if (entry == null) {
			logger.error("Source set $sourceSetName has ${entries.size} @CompatEntry objects; at most one is allowed")
			return emptyList()
		}
		written = true
		val className = "GeneratedCompat${sourceSetName.replaceFirstChar { it.uppercaseChar() }}"
		val deps = Dependencies(true, *sources.toTypedArray())
		val packageList = claimed.joinToString(", ") { "\"" + it + "\"" }
		val text = buildString {
			appendLine("// This file is @generated by SubscribeAnnotationProcessor")
			appendLine("// Do not edit")
			appendLine("package $ownPackage")
			appendLine("class $className : dev.ashtonite365.apex.util.compatloader.CompatOwnership {")
			appendLine()
			appendLine("\toverride fun ownsClass(className: String): Boolean {")
			appendLine("\t\treturn dev.ashtonite365.apex.util.compatloader.PackageOwnership.inPackages(className, $packageList)")
			appendLine("\t}")
			appendLine()
			appendLine("\toverride val switchObject: dev.ashtonite365.apex.util.compatloader.CompatSwitch")
			appendLine("\t\tget() = ${entry.qualifiedName!!.asString()}")
			appendLine()
			appendLine("}")
		}
		codeGenerator.createNewFile(deps, ownPackage, className).bufferedWriter().use { it.write(text) }
		codeGenerator.createNewFileByPath(deps, "META-INF/services/dev.ashtonite365.apex.util.compatloader.CompatOwnership", "")
			.bufferedWriter().use { it.write("$ownPackage.$className\n") }
		return emptyList()
	}

	@AutoService(SymbolProcessorProvider::class)
	class Provider : SymbolProcessorProvider {
		override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor =
			CompatMetaProcessor(environment.logger, environment.codeGenerator, environment.options["apex.sourceset"] ?: "main")
	}
}
