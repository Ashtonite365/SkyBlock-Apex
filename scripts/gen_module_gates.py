"""Phase O5: generate src/main/kotlin/modules/ModuleGates.kt from scripts/modules/mixin-gates.tsv.

One @JvmField @Volatile Boolean per gated module (true until ModuleManager has evaluated the modules), read by mixins
as ModuleGates.<field>. Usage: python3 scripts/gen_module_gates.py [--check]
"""
import re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'scripts/modules/mixin-gates.tsv'
OUT = ROOT / 'src/main/kotlin/modules/ModuleGates.kt'


def field(module):
	head, *rest = module.split('-')
	return head + ''.join(p[:1].upper() + p[1:] for p in rest)


def modules():
	rows = [l.split('\t') for l in SRC.read_text().splitlines() if l and not l.startswith('#')][1:]
	seen = []
	for _, m in rows:
		if m not in seen: seen.append(m)
	return sorted(seen)


def render(mods):
	out = ['// SPDX-License-Identifier: GPL-3.0-or-later',
		'// GENERATED by scripts/gen_module_gates.py from scripts/modules/mixin-gates.tsv (phase O5). Do not edit; regenerate.',
		'package dev.ashtonite365.apex.modules', '',
		'/**',
		' * One flag per module whose mixins are gated (DESIGN.md 5.5). Mixins read the field directly, so there is no map',
		' * lookup per frame. Every flag starts true (today\'s behaviour) and follows the module\'s effective state once',
		' * [ModuleManager] has evaluated the modules.',
		' */',
		'object ModuleGates {']
	for m in mods: out += [f'\t/** `{m}` */', '\t@JvmField @Volatile var ' + field(m) + ' = true']
	out += ['', '\t/** Module ids that have a gate, in field order. */',
		'\tval ids: List<String> = listOf(' + ', '.join(f'"{m}"' for m in mods) + ')', '',
		'\t/** Sets the gate of [id]; false when [id] has no gate. */',
		'\tfun set(id: String, active: Boolean): Boolean {', '\t\twhen (id) {']
	for m in mods: out.append(f'\t\t\t"{m}" -> {field(m)} = active')
	out += ['\t\t\telse -> return false', '\t\t}', '\t\treturn true', '\t}', '',
		'\t/** Current value of the gate of [id], or null when it has none. */',
		'\tfun get(id: String): Boolean? = when (id) {']
	for m in mods: out.append(f'\t\t"{m}" -> {field(m)}')
	out += ['\t\telse -> null', '\t}', '}', '']
	return '\n'.join(out)


if __name__ == '__main__':
	text = render(modules())
	if '--check' in sys.argv: sys.exit(0 if OUT.is_file() and OUT.read_text() == text else 1)
	OUT.write_text(text); print(OUT, len(modules()), 'gates')
